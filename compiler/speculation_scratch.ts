/** Relocatable scratch shared by speculation's bitmap and the heredoc queue. */
export const speculationScratch = `
  (global $specScratch (mut i32) (i32.const 0))
  (global $specScratchSize (mut i32) (i32.const 0))
  (global $specTagOffset (mut i32) (i32.const 0))
  (global $specBytes (mut i32) (i32.const 0))
  (global $queueCapacity (mut i32) (i32.const 0))
  (global $queueUsed (mut i32) (i32.const 0))
  (global $scratchRequired (export "scratchRequired") (mut i64) (i64.const 0))
  (func $scratchResize (param $capacity i32) (param $end i64)
    (local $old i32) (local $next i32) (local $oldQueue i32) (local $newQueue i32)
    (local $size i64) (local $required i64) (local $available i64) (local $preferred i64)
    (local $pages i32) (local $minimum i32)
    (local.set $size (i64.add (i64.extend_i32_u (global.get $specScratchSize)) (i64.extend_i32_u (local.get $capacity))))
    (local.set $required (i64.add (local.get $end) (local.get $size)))
    (if (i64.gt_u (local.get $required) (i64.const 4294967296)) (then (call $fail)))
    (if (i64.gt_u (local.get $required) (global.get $scratchRequired)) (then (global.set $scratchRequired (local.get $required))))
    (local.set $available (i64.shl (i64.extend_i32_u (memory.size)) (i64.const 16)))
    (local.set $old (global.get $specScratch))
    (local.set $oldQueue (i32.add (local.get $old) (global.get $specScratchSize)))
    (if (i64.gt_u (local.get $required) (local.get $available)) (then
      (local.set $minimum (i32.wrap_i64 (i64.shr_u (i64.add (i64.sub (local.get $required) (local.get $available)) (i64.const 65535)) (i64.const 16))))
      (local.set $preferred (i64.add (local.get $required) (local.get $size)))
      (if (i64.gt_u (local.get $preferred) (i64.const 4294967296)) (then (local.set $preferred (i64.const 4294967296))))
      (local.set $pages (i32.wrap_i64 (i64.shr_u (i64.add (i64.sub (local.get $preferred) (local.get $available)) (i64.const 65535)) (i64.const 16))))
      (if (i32.eq (memory.grow (local.get $pages)) (i32.const -1)) (then
        (if (i32.eq (memory.grow (local.get $minimum)) (i32.const -1)) (then (call $fail)))))))
    (local.set $next (i32.wrap_i64 (i64.sub (i64.shl (i64.extend_i32_u (memory.size)) (i64.const 16)) (local.get $size))))
    (local.set $newQueue (i32.add (local.get $next) (global.get $specScratchSize)))
    (if (i32.ne (local.get $next) (local.get $old)) (then
      (if (i32.gt_u (local.get $next) (local.get $old))
        (then
          (memory.copy (local.get $newQueue) (local.get $oldQueue) (global.get $queueUsed))
          (memory.copy (local.get $next) (local.get $old) (global.get $specScratchSize)))
        (else
          (memory.copy (local.get $next) (local.get $old) (global.get $specScratchSize))
          (memory.copy (local.get $newQueue) (local.get $oldQueue) (global.get $queueUsed))))))
    (global.set $specScratch (local.get $next))
    (global.set $queueCapacity (local.get $capacity)))
  (func $scratchInit (param $out i32) (param $length i32) (param $spec i32)
    (local $bytes i64) (local $offset i64) (local $size i64)
    (global.set $queueCapacity (i32.const 0)) (global.set $queueUsed (i32.const 0))
    (global.set $specScratchSize (i32.const 0)) (global.set $specTagOffset (i32.const 0))
    (global.set $specScratch (i32.wrap_i64 (i64.shl (i64.extend_i32_u (memory.size)) (i64.const 16))))
    (global.set $scratchRequired (i64.const 0))
    (if (local.get $spec) (then
      (local.set $bytes (i64.shr_u (i64.add (i64.extend_i32_u (local.get $length)) (i64.const 7)) (i64.const 3)))
      (global.set $specBytes (i32.wrap_i64 (local.get $bytes)))
      (local.set $offset (i64.and (i64.add (i64.mul (local.get $bytes) (i64.extend_i32_u (local.get $spec))) (i64.const 3)) (i64.const -4)))
      (local.set $size (i64.add (local.get $offset) (i64.shl (i64.mul (local.get $bytes) (i64.extend_i32_u (local.get $spec))) (i64.const 2))))
      (if (i64.eqz (local.get $size)) (then (local.set $size (i64.const 8))))
      (if (i64.gt_u (local.get $size) (i64.const 4294967295)) (then (call $fail)))
      (global.set $specTagOffset (i32.wrap_i64 (local.get $offset)))))
    (call $scratchResize (i32.wrap_i64 (local.get $size)) (i64.extend_i32_u (local.get $out)))
    (global.set $specScratchSize (i32.wrap_i64 (local.get $size)))
    (global.set $queueCapacity (i32.const 0))
    (memory.fill (global.get $specScratch) (i32.const 0) (global.get $specScratchSize)))
  (func $specScratchInit (param $out i32) (param $length i32)
    (call $scratchInit (local.get $out) (local.get $length) (i32.const 1)))
  (func $specReserveOutput (param $end i64)
    (call $scratchResize (global.get $queueCapacity) (local.get $end)))
  (func $specBits (result i32) (global.get $specScratch))
  (func $specTags (result i32) (i32.add (global.get $specScratch) (global.get $specTagOffset)))
  (func $specGroupBits (param $group i32) (result i32)
    (i32.add (call $specBits) (i32.mul (local.get $group) (global.get $specBytes))))
  (func $specGroupTags (param $group i32) (result i32)
    (i32.add (call $specTags) (i32.shl (i32.mul (local.get $group) (global.get $specBytes)) (i32.const 2))))`;
