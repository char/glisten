import {
  byte,
  byteSet,
  bytes,
  choice,
  classify,
  defineGrammar,
  except,
  keywordTable,
  lineStart,
  literal,
  lookahead,
  notNext,
  on,
  oneOf,
  optional,
  paint,
  popState,
  pushState,
  range,
  redispatch,
  repeat,
  setState,
  token,
  union,
} from "#/grammar/mod.ts";

const all = byteSet({ ranges: [[0, 255]] });
const digit = range("0", "9");
const start = union("_", range("a", "z"), range("A", "Z"), byteSet({ ranges: [[128, 255]] }));
const rest = union(start, digit);
const ident = [byte(start), bytes(rest, { min: 0 })];
const space = bytes(" \t\r\n");
const optionalSpace = bytes(" \t\r\n", { min: 0 });
const digits = (set: typeof digit) => [byte(set), repeat(bytes("_", { min: 0 }), byte(set))];
const decimal = digits(digit);
const hex = digits(union(digit, range("a", "f"), range("A", "F")));
const binary = digits("01");
const exponent = [byte("eE"), optional(byte("+-")), ...decimal];
const hard = [
  "as",
  "break",
  "class",
  "continue",
  "do",
  "else",
  "for",
  "fun",
  "if",
  "in",
  "interface",
  "is",
  "object",
  "package",
  "import",
  "return",
  "super",
  "this",
  "throw",
  "try",
  "typealias",
  "val",
  "var",
  "when",
  "while",
];
const modifiers = [
  "abstract",
  "actual",
  "annotation",
  "companion",
  "const",
  "crossinline",
  "data",
  "enum",
  "expect",
  "external",
  "final",
  "infix",
  "inline",
  "inner",
  "internal",
  "lateinit",
  "noinline",
  "open",
  "operator",
  "override",
  "private",
  "protected",
  "public",
  "reified",
  "sealed",
  "suspend",
  "tailrec",
  "value",
  "vararg",
];
const declarations = [
  "class",
  "interface",
  "object",
  "fun",
  "val",
  "var",
  "constructor",
  "typealias",
  "get",
  "set",
];
const words = [
  ...keywordTable(hard, "keyword"),
  ...keywordTable(["true", "false", "null"], "constant.builtin"),
];
const wordChoice = (values: readonly string[]) =>
  choice(...values.map((value) => [literal(value), notNext(rest)]));
const escape = on(
  "\\",
  literal("\\"),
  choice(
    [literal("u"), bytes(union(digit, range("a", "f"), range("A", "F")), { min: 4, max: 4 })],
    [byte("tbnr'\"\\$")],
  ),
  paint("string.escape"),
);
const interpolation = [
  token("${", "punctuation.special", pushState("template")),
  on("$", literal("$"), ...ident, paint("variable")),
];
const code = [
  on("#", lineStart(), literal("#!"), paint("comment"), pushState("lineComment")),
  token("//", "comment", pushState("lineComment")),
  token("/*", "comment", pushState("blockComment")),
  token('"""', "string", pushState("rawString")),
  token('"', "string", pushState("string")),
  token("'", "string", pushState("char")),
  token("`", "variable", pushState("escapedName")),
  on(
    "@",
    literal("@"),
    optional(
      wordChoice([
        "file",
        "field",
        "property",
        "get",
        "set",
        "receiver",
        "param",
        "setparam",
        "delegate",
      ]),
      literal(":"),
    ),
    ...ident,
    repeat(literal("."), ...ident),
    paint("attribute"),
  ),
  on(
    "bcrst",
    wordChoice(["break", "continue", "return", "super", "this"]),
    literal("@"),
    paint("keyword"),
    pushState("label"),
  ),
  on(start, ...ident, literal("@"), paint("label")),
  on(
    "0123456789",
    choice(
      [
        literal("0"),
        byte("xX"),
        ...hex,
        optional(choice([byte("uU"), optional(literal("L"))], [literal("L")])),
      ],
      [
        literal("0"),
        byte("bB"),
        ...binary,
        optional(choice([byte("uU"), optional(literal("L"))], [literal("L")])),
      ],
      [...decimal, literal("."), ...decimal, optional(...exponent), optional(byte("fF"))],
      [...decimal, ...exponent, optional(byte("fF"))],
      [...decimal, byte("fF")],
      [...decimal, optional(choice([byte("uU"), optional(literal("L"))], [literal("L")]))],
    ),
    notNext(rest),
    paint("number"),
  ),
  on("ip", wordChoice(["import", "package"]), paint("keyword"), pushState("qualified")),
  on(
    "f",
    literal("fun"),
    notNext(rest),
    lookahead(space, literal("interface"), notNext(rest)),
    paint("keyword"),
  ),
  on("f", literal("fun"), notNext(rest), lookahead(space), paint("keyword"), pushState("funHead")),
  on(
    "ciot",
    wordChoice(["class", "interface", "object", "typealias"]),
    lookahead(space, byte(start)),
    paint("keyword"),
    pushState("typeName"),
  ),
  on(
    start,
    ...ident,
    lookahead(space, repeat(wordChoice(modifiers), space), wordChoice(declarations)),
    classify(keywordTable(modifiers, "keyword"), [paint("variable")]),
  ),
  on(
    "c",
    literal("catch"),
    notNext(rest),
    lookahead(optionalSpace, literal("(")),
    paint("keyword"),
  ),
  on(
    "f",
    literal("finally"),
    notNext(rest),
    lookahead(optionalSpace, literal("{")),
    paint("keyword"),
  ),
  on("i", literal("init"), notNext(rest), lookahead(optionalSpace, literal("{")), paint("keyword")),
  on(
    "c",
    literal("constructor"),
    notNext(rest),
    lookahead(optionalSpace, literal("(")),
    paint("keyword"),
  ),
  on(
    "gs",
    wordChoice(["get", "set"]),
    lookahead(
      optionalSpace,
      literal("("),
      bytes(except(all, ")\r\n"), { min: 0 }),
      literal(")"),
      optionalSpace,
      byte("={"),
    ),
    paint("keyword"),
  ),
  on(
    "w",
    literal("where"),
    notNext(rest),
    lookahead(space, ...ident, optionalSpace, literal(":")),
    paint("keyword"),
  ),
  on(
    "b",
    literal("by"),
    notNext(rest),
    lookahead(space, byte(union(start, "({\"'"))),
    paint("keyword"),
  ),
  on(
    range("A", "Z"),
    ...ident,
    lookahead(literal("<"), optionalSpace, byte(union(start, "*"))),
    paint("type"),
    pushState("typeOpen"),
  ),
  on(start, ...ident, lookahead(optionalSpace, literal("(")), classify(words, [paint("function")])),
  on(range("A", "Z"), ...ident, classify(words, [paint("type")])),
  on(start, ...ident, lookahead(optionalSpace, literal("{")), classify(words, [paint("function")])),
  on(start, ...ident, classify(words, [paint("variable")])),
  token("?.", "operator", pushState("member")),
  ...[
    "?:",
    "!!",
    "->",
    "::",
    "===",
    "!==",
    "==",
    "!=",
    "<=",
    ">=",
    "&&",
    "||",
    "..<",
    "..",
    "+=",
    "-=",
    "*=",
    "/=",
    "%=",
    "++",
    "--",
  ].map((value) => token(value, "operator")),
  token(oneOf("()[]{}"), "punctuation.bracket"),
  token(".", "punctuation.delimiter", pushState("member")),
  token(oneOf(",;:"), "punctuation.delimiter"),
  token(oneOf("+-*/%=!<>&|^?"), "operator"),
];

export default defineGrammar({
  name: "kotlin",
  aliases: ["kt", "kts"],
  initial: "root",
  states: {
    root: { style: "plain", arms: code },
    funHead: {
      style: "plain",
      arms: [
        on(start, ...ident, lookahead(optionalSpace, literal("(")), paint("function"), popState()),
        token("<", "punctuation.bracket", pushState("typeArgs")),
        token("(", "punctuation.bracket", popState()),
        on("\n", literal("\n"), paint("plain")),
        ...code,
      ],
    },
    qualified: {
      style: "plain",
      arms: [
        redispatch("\n", popState()),
        token(";", "punctuation.delimiter", popState()),
        on("a", literal("as"), notNext(rest), paint("keyword")),
        on(start, ...ident, paint("variable")),
        token(".", "punctuation.delimiter"),
        token("*", "operator"),
      ],
    },
    typeName: {
      style: "plain",
      arms: [
        on(" \t\r\n", bytes(" \t\r\n"), paint("plain")),
        on(
          start,
          ...ident,
          lookahead(literal("<"), optionalSpace, byte(union(start, "*"))),
          paint("type"),
          setState("typeOpen"),
        ),
        on(start, ...ident, paint("type"), popState()),
      ],
      otherwise: [popState()],
    },
    member: {
      style: "plain",
      arms: [
        on(" \t\r\n", bytes(" \t\r\n"), paint("plain")),
        on(
          start,
          ...ident,
          lookahead(optionalSpace, choice([literal("(")], [literal("{")])),
          paint("function"),
          popState(),
        ),
        on(
          range("A", "Z"),
          ...ident,
          lookahead(literal("<"), optionalSpace, byte(union(start, "*"))),
          paint("type"),
          setState("typeOpen"),
        ),
        on(range("A", "Z"), ...ident, paint("type"), popState()),
        on(start, ...ident, paint("variable.member"), popState()),
      ],
      otherwise: [popState()],
    },
    typeOpen: { style: "plain", arms: [token("<", "punctuation.bracket", setState("typeArgs"))] },
    typeArgs: {
      style: "plain",
      arms: [
        token(">", "punctuation.bracket", popState()),
        on("or", wordChoice(["out", "reified"]), notNext(rest), paint("keyword")),
        ...code,
      ],
    },
    template: {
      style: "plain",
      arms: [
        token("}", "punctuation.special", popState()),
        token("{", "punctuation.bracket", pushState("templateBrace")),
        ...code,
      ],
    },
    templateBrace: {
      style: "plain",
      arms: [
        token("}", "punctuation.bracket", popState()),
        token("{", "punctuation.bracket", pushState("templateBrace")),
        ...code,
      ],
    },
    string: {
      style: "string",
      arms: [
        escape,
        ...interpolation,
        token('"', "string", popState()),
        redispatch("\n", popState()),
      ],
    },
    rawString: { style: "string", arms: [...interpolation, token('"""', "string", popState())] },
    char: {
      style: "string",
      arms: [escape, token("'", "string", popState()), redispatch("\n", popState())],
    },
    escapedName: {
      style: "variable",
      arms: [token("`", "variable", popState()), redispatch("\n", popState())],
    },
    label: {
      style: "label",
      arms: [on(start, ...ident, paint("label"), popState())],
      otherwise: [popState()],
    },
    lineComment: { style: "comment", arms: [redispatch("\n", popState())] },
    blockComment: {
      style: "comment",
      arms: [token("/*", "comment", pushState("blockComment")), token("*/", "comment", popState())],
    },
  },
});
